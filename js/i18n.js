/* Every key in any language, for the missing-translation test. */
export const I18N_TABLE = I18N;

export const LANGS = ['zh', 'en', 'ja'];

let lang = 'en';

export function t(key, params){
  let s = (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
  const p = Object.assign({device: CONFIG.deviceName}, params || {});
  for (const k in p) s = s.split('{'+k+'}').join(p[k]);
  return s;
}

export function getLang(){ return lang; }

export function errText(e){
  if (e && e.i18nKey) return t(e.i18nKey, e.i18nParams);
  return String((e && e.message) || e);
}

/* Applies the language to every element carrying data-i18n / data-i18n-html /
 * data-i18n-ph, and remembers the choice. Called again after any DOM the app
 * builds at runtime (the tracker list, for example) so late-created nodes are
 * covered too. */
export function applyLang(l){
  lang = LANGS.includes(l) ? l : 'en';
  try { localStorage.setItem('lang', lang); } catch (_) {}
  document.documentElement.lang = lang === 'zh' ? 'zh-Hant' : lang;
  for (const el of document.querySelectorAll('[data-i18n]')){
    el.textContent = t(el.dataset.i18n);
  }
  for (const el of document.querySelectorAll('[data-i18n-html]')){
    el.innerHTML = t(el.dataset.i18nHtml);
  }
  for (const el of document.querySelectorAll('[data-i18n-ph]')){
    el.placeholder = t(el.dataset.i18nPh);
  }
}

export function detectLang(){
  try {
    const saved = localStorage.getItem('lang');
    if (LANGS.includes(saved)) return saved;
  } catch (_) {}
  const n = (navigator.language || 'en').toLowerCase();
  if (n.startsWith('zh')) return 'zh';
  if (n.startsWith('ja')) return 'ja';
  return 'en';
}
